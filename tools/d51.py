# fixups: 0x10 JBC bit,rel=3 ; 0x20 JB=3 ; 0x30 JNB=3; 0x73 JMP@A+DPTR=1; 0xa5 reserved
def rel(pc,b): return (pc+((b^0x80)-0x80))&0xffff
def flow(code,pc):
    o=code[pc]; n=L[o]; nxt=pc+n; t=[]; stop=False
    if o&0x1f==0x01: t=[((pc+2)&0xf800)|((o>>5)<<8)|code[pc+1]]; stop=True     # AJMP
    elif o&0x1f==0x11: t=[((pc+2)&0xf800)|((o>>5)<<8)|code[pc+1]]               # ACALL
    elif o==0x02: t=[code[pc+1]<<8|code[pc+2]]; stop=True
    elif o==0x12: t=[code[pc+1]<<8|code[pc+2]]
    elif o==0x80: t=[rel(nxt,code[pc+1])]; stop=True
    elif o in (0x22,0x32,0x73): stop=True
    elif o in (0x40,0x50,0x60,0x70) or 0xd8<=o<=0xdf: t=[rel(nxt,code[pc+1])]
    elif o in (0x10,0x20,0x30) or 0xb4<=o<=0xbf or o==0xd5: t=[rel(nxt,code[pc+2])]
    return n,t,stop
def disasm(code,entries):
    seen={}; work=list(entries); calls=set()
    while work:
        pc=work.pop()
        while 0<=pc<len(code) and pc not in seen:
            n,t,stop=flow(code,pc); seen[pc]=n
            o=code[pc]
            if o==0x12 or o&0x1f==0x11: calls.update(t)
            work+= [x for x in t if x<len(code)]
            if stop: break
            pc+=n
    return seen,calls
def xwrites(code,seen):
    """track MOV DPTR,#imm / MOV A,#imm / INC DPTR / MOVX @DPTR,A / ORL/ANL A,# within straight-line code"""
    out=[]; dptr=None; a=None; last=None
    for pc in sorted(seen):
        o=code[pc]; n=seen[pc]
        if last is not None and pc!=last: dptr=a=None
        last=pc+n
        if o==0x90: dptr=code[pc+1]<<8|code[pc+2]
        elif o==0xa3 and dptr is not None: dptr+=1
        elif o==0x74: a=('=',code[pc+1])
